async function resetToOldRow(withVerifier: boolean): Promise<void> {
  await prisma.$executeRawUnsafe("delete from crypto_config");
  let vaultVerifier: string | null = null;
  if (withVerifier) {
    const vk = combineAndStretchKey(key, await deriveArgon2Key("old-passphrase-for-the-old-seed"));
    vaultVerifier = encryptWithVaultKey(OLD_FP, vk);
  }
  await prisma.cryptoConfig.create({
    data: { id: 1, encryptedMasterSeed: encryptSeed(oldSeed, key), seedFingerprint: OLD_FP, vaultVerifier, hotWalletAddressTrc20: "T-old-hot", hotWalletAddressBep20: "0xold-hot", createdAt: new Date(Date.now() - 86_400_000) },
  });
  wipeMasterSeedCache();
}

