// ─── CLI through a pseudo-terminal
interface PtyRun { code: number | null; out: string }
/** Runs `tsx <script> <args>` inside `script` (a real pty). `steps`: when the output matches re, type text + Enter. */
function runInPty(scriptPath: string, args: string[], steps: Array<[RegExp, string]>, tag: string): Promise<PtyRun> {
  const cmd = ["./node_modules/.bin/tsx", scriptPath, ...args].map((a) => `'${a.replace(/'/g, "'\\''")}'`).join(" ");
  const transcript = join(RUN, `${tag}.typescript`);
  return new Promise((resolve) => {
    const child = spawn("script", ["-q", "-e", "-c", cmd, transcript], { stdio: ["pipe", "pipe", "pipe"], env: process.env });
    let out = "";
    let next = 0;
    let busy = false;
    const pump = () => {
      if (busy) return;
      const step = steps[next];
      if (!step) return;
      const tail = out.slice(-400);
      if (!step[0].test(tail)) return;
      busy = true;
      next += 1;
      // Keystrokes as a human types them, one chunk after the prompt appeared.
      setTimeout(() => { child.stdin.write(`${step[1]}\r`); busy = false; setTimeout(pump, 150); }, 120);
    };
    child.stdout.on("data", (d: Buffer) => { out += d.toString("utf8"); pump(); });
    child.stderr.on("data", (d: Buffer) => { out += d.toString("utf8"); });
    const timer = setTimeout(() => child.kill("SIGTERM"), 90_000);
    child.on("close", (code) => { clearTimeout(timer); writeFileSync(join(RUN, `${tag}.out`), out); resolve({ code, out }); });
  });
}

/** A backup fixture the gate accepts: the runbook's plain samapay-<stamp>.dump, > 10 KiB, no sidecar. */
function freshBackup(): string {
  const d = new Date(Date.now() + 2000);
  const stamp = d.toISOString().replace(/[-:]/g, "").replace(/\.\d{3}Z$/, "Z");
  const s = `${stamp.slice(0, 4)}-${stamp.slice(4, 6)}-${stamp.slice(6, 11)}${stamp.slice(11)}`;
  const p = join(BACKUP_DIR, `samapay-${s}.dump`);
  writeFileSync(p, crypto.randomBytes(20_000));
  const t = (d.getTime() + 1000) / 1000;
  utimesSync(p, t, t);
  return p;
}
/**
 * What the terminal showed after each "word N of 24: " prompt, up to the line end.
 * In cooked (echo ON) mode the kernel echoes the typed word right there; with echo
 * OFF every one of these is empty. Returns the prompts that showed anything.
 * (Not a search of the whole output for mnemonic words: BIP39 words are common
 * English — "again", "list", "type" — and the script's own text can contain them.)
 */
function echoedAfterPrompts(text: string): { prompts: number; echoed: number } {
  const all = [...text.matchAll(/word \d+ of 24: ([^\r\n]*)/g)];
  return { prompts: all.length, echoed: all.filter((m) => (m[1] ?? "").length > 0).length };
}

